// Command genproviderkeys builds internal/quorum/provider_keys.yaml from the
// dRPC provider-config: values.yaml gives the providers and the order of nodes
// inside each region, the rsaKeys map of secrets.yaml gives the public keys.
//
// secrets.yaml is encrypted with sops, so the keys come in already decrypted:
//
//	sops -d --extract '["rsaKeys"]' <infra>/configs/provider-config/secrets.yaml |
//	    go run ./cmd/genproviderkeys -values <infra>/configs/provider-config/values.yaml -keys -
//
// `make provider-keys INFRA=<path to the infra repo>` runs exactly that.
package main

import (
	"bytes"
	"crypto/x509"
	"encoding/base64"
	"encoding/pem"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path"
	"sort"
	"strings"

	"github.com/drpcorg/nodecore/internal/quorum"
	"gopkg.in/yaml.v3"
)

const header = `# Code generated by cmd/genproviderkeys from the dRPC provider-config. DO NOT EDIT.
# Regenerate with ` + "`make provider-keys INFRA=<path to the infra repo>`" + `.
# Raw base64-encoded X.509 SubjectPublicKeyInfo (DER), no PEM header/footer.
# Keys are fully-qualified provider ids in the form <name>@<region>#<idx>,
# where <idx> is the 0-based position of the node inside its region in
# values.yaml. Matches exactly what dproxy puts in the QR<N>-id-* header.
`

type valuesFile struct {
	ProviderConfig struct {
		Providers []struct {
			Name    string `yaml:"name"`
			Cluster map[string]struct {
				Nodes []struct {
					PublicKey string `yaml:"public_key"`
				} `yaml:"nodes"`
			} `yaml:"cluster"`
		} `yaml:"providers"`
	} `yaml:"providerConfig"`
}

type entry struct {
	ProviderID string `yaml:"provider_id"`
	PublicKey  string `yaml:"public_key"`
}

func main() {
	valuesPath := flag.String("values", "", "path to provider-config values.yaml")
	keysPath := flag.String("keys", "", "decrypted rsaKeys map of provider-config secrets.yaml, - for stdin")
	outPath := flag.String("out", "internal/quorum/provider_keys.yaml", "file to write")
	check := flag.Bool("check", false, "do not write, exit 1 when -out is out of date")
	flag.Parse()

	if err := run(*valuesPath, *keysPath, *outPath, *check); err != nil {
		fmt.Fprintln(os.Stderr, "genproviderkeys:", err)
		os.Exit(1)
	}
}

func run(valuesPath, keysPath, outPath string, check bool) error {
	if valuesPath == "" || keysPath == "" {
		return errors.New("both -values and -keys are required")
	}
	valuesRaw, err := os.ReadFile(valuesPath)
	if err != nil {
		return err
	}
	var keysRaw []byte
	if keysPath == "-" {
		keysRaw, err = io.ReadAll(os.Stdin)
	} else {
		keysRaw, err = os.ReadFile(keysPath)
	}
	if err != nil {
		return err
	}

	entries, err := build(valuesRaw, keysRaw)
	if err != nil {
		return err
	}
	out, err := render(entries)
	if err != nil {
		return err
	}

	current, err := os.ReadFile(outPath)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	report, changed := diffReport(current, entries)
	fmt.Print(report)
	if check {
		if changed || !bytes.Equal(current, out) {
			return fmt.Errorf("%s is out of date", outPath)
		}
		return nil
	}
	return os.WriteFile(outPath, out, 0o644)
}

// build lists every node of every provider as <name>@<region>#<idx> with the
// key its public_key path points to. A node whose key is missing or unreadable
// is an error, all of them are reported at once.
func build(valuesRaw, keysRaw []byte) ([]entry, error) {
	var values valuesFile
	if err := yaml.Unmarshal(valuesRaw, &values); err != nil {
		return nil, fmt.Errorf("parse values: %w", err)
	}
	var secrets map[string]string
	if err := yaml.Unmarshal(keysRaw, &secrets); err != nil {
		return nil, fmt.Errorf("parse keys, expected the rsaKeys map of name to base64 PEM: %w", err)
	}
	if len(secrets) == 0 {
		return nil, errors.New("no keys on input")
	}

	derByName := make(map[string]string)
	var entries []entry
	var errs []error
	for _, provider := range values.ProviderConfig.Providers {
		for region, cluster := range provider.Cluster {
			for idx, node := range cluster.Nodes {
				id := fmt.Sprintf("%s@%s#%d", provider.Name, region, idx)
				name := path.Base(node.PublicKey)
				der, ok := derByName[name]
				if !ok {
					secret, found := secrets[name]
					if node.PublicKey == "" || !found {
						errs = append(errs, fmt.Errorf("%s: no key %q", id, node.PublicKey))
						continue
					}
					raw, err := pkixDER(secret)
					if err != nil {
						errs = append(errs, fmt.Errorf("%s: key %q: %w", id, name, err))
						continue
					}
					der = base64.StdEncoding.EncodeToString(raw)
					derByName[name] = der
				}
				entries = append(entries, entry{ProviderID: id, PublicKey: der})
			}
		}
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].ProviderID < entries[j].ProviderID })
	return entries, nil
}

// pkixDER turns a secret value (base64 of a PEM file, as Kubernetes Secret
// data holds it) into the DER SubjectPublicKeyInfo the registry expects.
func pkixDER(secret string) ([]byte, error) {
	pemBytes, err := base64.StdEncoding.DecodeString(strings.TrimSpace(secret))
	if err != nil {
		return nil, fmt.Errorf("decode base64: %w", err)
	}
	block, _ := pem.Decode(pemBytes)
	if block == nil {
		return nil, errors.New("no PEM block")
	}
	var pub any
	switch block.Type {
	case "PUBLIC KEY":
		pub, err = x509.ParsePKIXPublicKey(block.Bytes)
	case "RSA PUBLIC KEY":
		pub, err = x509.ParsePKCS1PublicKey(block.Bytes)
	case "CERTIFICATE":
		var cert *x509.Certificate
		if cert, err = x509.ParseCertificate(block.Bytes); err == nil {
			pub = cert.PublicKey
		}
	default:
		return nil, fmt.Errorf("unsupported PEM block %q", block.Type)
	}
	if err != nil {
		return nil, err
	}
	return x509.MarshalPKIXPublicKey(pub)
}

// render writes the file and loads it back through the registry nodecore
// embeds, so a file nodecore cannot start with is never written.
func render(entries []entry) ([]byte, error) {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("keys:\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "  - provider_id: %s\n    public_key: %s\n", e.ProviderID, e.PublicKey)
	}
	out := []byte(b.String())
	reg, err := quorum.LoadRegistry(out)
	if err != nil {
		return nil, err
	}
	if reg.Len() != len(entries) {
		return nil, fmt.Errorf("registry loaded %d keys of %d", reg.Len(), len(entries))
	}
	return out, nil
}

// diffReport lists provider ids added, removed and with a new key against the
// current file and tells whether anything changed.
func diffReport(current []byte, entries []entry) (string, bool) {
	var file struct {
		Keys []entry `yaml:"keys"`
	}
	_ = yaml.Unmarshal(current, &file)
	old := make(map[string]string, len(file.Keys))
	for _, e := range file.Keys {
		old[e.ProviderID] = e.PublicKey
	}

	var added, rekeyed, removed []string
	seen := make(map[string]bool, len(entries))
	for _, e := range entries {
		seen[e.ProviderID] = true
		switch key, ok := old[e.ProviderID]; {
		case !ok:
			added = append(added, e.ProviderID)
		case key != e.PublicKey:
			rekeyed = append(rekeyed, e.ProviderID)
		}
	}
	for id := range old {
		if !seen[id] {
			removed = append(removed, id)
		}
	}
	sort.Strings(removed)

	var b strings.Builder
	fmt.Fprintf(&b, "%d keys: %d added, %d new key, %d removed\n", len(entries), len(added), len(rekeyed), len(removed))
	for _, group := range []struct {
		sign string
		ids  []string
	}{{"+", added}, {"~", rekeyed}, {"-", removed}} {
		for _, id := range group.ids {
			fmt.Fprintf(&b, "  %s %s\n", group.sign, id)
		}
	}
	return b.String(), len(added)+len(rekeyed)+len(removed) > 0
}
